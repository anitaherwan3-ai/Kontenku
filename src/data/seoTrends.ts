// Helper: Calculate Real-time SEO script score
export function analyzeStoryboardSEO(
  scenes: { voiceoverText: string; onScreenText: string; sceneType: string }[],
  categoryName?: string
) {
  const fullText = scenes
    .map((s) => `${s.voiceoverText} ${s.onScreenText}`)
    .join(' ')
    .toLowerCase();

  const hookText = (scenes[0]?.voiceoverText || '' + ' ' + (scenes[0]?.onScreenText || '')).toLowerCase();
  const ctaText = (scenes[scenes.length - 1]?.voiceoverText || '' + ' ' + (scenes[scenes.length - 1]?.onScreenText || '')).toLowerCase();

  const relevantKeywords = TRENDING_SEO_KEYWORDS.filter(
    (k) => !categoryName || k.category.toLowerCase().includes(categoryName.toLowerCase()) || categoryName.toLowerCase().includes(k.category.toLowerCase()) || k.platform === 'all'
  );

  const matchedKeywords: string[] = [];
  const missingKeywords: string[] = [];

  TRENDING_SEO_KEYWORDS.forEach((kw) => {
    const cleanWord = kw.keyword.toLowerCase();
    const parts = cleanWord.split(' ');
    // Match if full keyword or at least 2 consecutive key tokens appear
    if (fullText.includes(cleanWord) || parts.some((p) => p.length > 4 && fullText.includes(p))) {
      if (!matchedKeywords.includes(kw.keyword)) {
        matchedKeywords.push(kw.keyword);
      }
    } else if (relevantKeywords.some((r) => r.id === kw.id)) {
      if (missingKeywords.length < 5) {
        missingKeywords.push(kw.keyword);
      }
    }
  });

  // Calculate scores
  let baseScore = 60;
  if (matchedKeywords.length >= 1) baseScore += 10;
  if (matchedKeywords.length >= 3) baseScore += 12;
  if (matchedKeywords.length >= 5) baseScore += 8;

  // Check Hook strength
  const hookHasKeyword = ['racun', 'review', 'rahasia', 'nemu', 'jangan', 'wajib', 'aesthetic', 'viral', 'tips', 'solusi', 'rekomendasi'].some((term) =>
    hookText.includes(term)
  );
  let hookSEOStrength: 'weak' | 'good' | 'viral_optimized' = 'weak';
  if (hookHasKeyword) {
    baseScore += 6;
    hookSEOStrength = 'good';
  }
  if (hookHasKeyword && (hookText.includes('keranjang') || hookText.includes('sebelum') || hookText.includes('under') || hookText.includes('jujur') || hookText.includes('ampuh'))) {
    baseScore += 4;
    hookSEOStrength = 'viral_optimized';
  }

  // Check CTA strength
  const ctaHasKeyword = ['keranjang kuning', 'link di bio', 'checkout', 'klaim', 'diskon', 'promo', 'order', 'sekarang', 'terbatas'].some((term) =>
    ctaText.includes(term)
  );
  if (ctaHasKeyword) {
    baseScore += 5;
  }

  const finalScore = Math.min(99, Math.max(45, baseScore));

  const recommendations: string[] = [];
  if (!hookHasKeyword) {
    recommendations.push('Tambahkan kata kunci Hook (misal: "Racun skincare", "Review jujur", atau "Nemu gadget") pada 3 detik pertama.');
  }
  if (!ctaHasKeyword) {
    recommendations.push('Perjelas kata kunci CTA (misal: "Checkout di keranjang kuning" atau "Klaim voucher di bio").');
  }
  if (matchedKeywords.length < 3) {
    recommendations.push('Tingkatkan variasi kata kunci pencarian e-commerce agar terindeks di TikTok Search & Reels explore.');
  }
  if (recommendations.length === 0) {
    recommendations.push('Naskah telah dioptimalkan dengan sangat baik untuk TikTok FYP & Reels search indexing!');
  }

  const suggestedHashtags = [
    '#TikTokShop',
    '#RacunTikTok',
    '#ViralDiTikTok',
    '#ReelsShopping',
    '#ReviewJujur',
    '#SpillProduk',
    '#BelanjaOnline',
    '#PromoFlashSale',
  ];

  return {
    overallScore: finalScore,
    matchedKeywords,
    missingHighImpactKeywords: missingKeywords,
    hookSEOStrength,
    keywordDensityPercent: parseFloat(((matchedKeywords.length / (scenes.length * 8)) * 100).toFixed(1)),
    recommendations,
    suggestedHashtags,
  };
}
